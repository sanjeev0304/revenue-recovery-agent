import type { ArmMetrics, MatrixCell, OpaqueSubset } from './metrics.js'
import type { EvalResults } from './results.js'

export function rupees(paise: number): string {
  const sign = paise < 0 ? '-' : ''
  const abs = Math.abs(paise)
  return `${sign}₹${Math.round(abs / 100).toLocaleString('en-IN')}`
}

export function rate(n: number, d: number): string {
  if (d === 0) return `${n}/0 (n/a)`
  return `${n}/${d} (${((100 * n) / d).toFixed(1)}%)`
}

function pct(n: number, d: number): string {
  if (d === 0) return 'n/a'
  return `${((100 * n) / d).toFixed(1)}%`
}

function ratio(n: number, d: number): string {
  if (d === 0) return 'n/a'
  return (n / d).toFixed(2)
}

function armRow(m: ArmMetrics): string {
  return [
    m.label,
    rate(m.recovered, m.processed),
    rupees(m.recoveredPaise),
    pct(m.recoveredPaise, m.totalPaise),
    String(m.chargeAttempts),
    String(m.wastedChargeAttempts),
    String(m.contacts),
    ratio(m.chargeAttempts, m.recovered),
  ].join(' | ')
}

function subsetRow(label: string, s: { total: number; correct: number }): string {
  return `| ${label} | ${rate(s.correct, s.total)} |`
}

function opaqueSection(o: OpaqueSubset): string {
  const majorityBaseline = rate(o.majorityCount, o.all.total)

  return [
    `Majority class inside this subset is \`${o.majorityCause}\` at ${majorityBaseline}. That is the number to beat; predicting the majority label on every opaque record scores exactly it.`,
    '',
    '| subset | accuracy |',
    '|---|---|',
    subsetRow('all opaque records', o.all),
    subsetRow('genuinely opaque (true cause is OPAQUE_BANK_DECLINE)', o.genuine),
    subsetRow('masked (true cause is something else)', o.masked),
    subsetRow('  masked, inside a downtime burst', o.maskedInBurst),
    subsetRow('  masked, scattered', o.maskedScattered),
    '',
    'Per-underlying-cause precision inside the masked subset is deliberately not reported: the masked records spread across eight causes with the rarest at one or two records, and a precision figure on cells that small would be noise presented as measurement.',
  ].join('\n')
}

function confusionSection(cells: MatrixCell[]): string {
  const errors = cells.filter((c) => c.predicted !== c.trueCause)
  const correct = cells.filter((c) => c.predicted === c.trueCause)

  const totalShortfall = errors.reduce((a, c) => a + c.shortfallPaise, 0)
  const totalWasted = errors.reduce((a, c) => a + c.wastedChargeAttempts, 0)

  const rows = (list: MatrixCell[]): string[] =>
    list.map((c) =>
      `| \`${c.predicted}\` | \`${c.trueCause}\` | ${c.n} | ${rupees(c.recoveredPaise)} | ${rupees(c.oracleRecoveredPaise)} | ${rupees(c.shortfallPaise)} | ${c.wastedChargeAttempts} | ${rupees(c.costPaise)} |`,
    )

  const header = [
    '| predicted | true | n | recovered | oracle would have | shortfall | wasted attempts | op. cost |',
    '|---|---|---|---|---|---|---|---|',
  ]

  return [
    'Every `(predicted, true)` cell is scored by running the predicted cause\'s playbook against that record\'s real `recoverableUnder`. "Oracle would have" is the same records scored under a run that knew the true cause, so the shortfall is what the misclassification actually cost in money rather than in accuracy points.',
    '',
    `Across all misclassified cells: ${rupees(totalShortfall)} forgone against the oracle, ${totalWasted} wasted charge attempts.`,
    '',
    '### Errors, most expensive first',
    '',
    ...header,
    ...rows([...errors].sort((a, b) => b.shortfallPaise - a.shortfallPaise)),
    '',
    '### Correct predictions',
    '',
    ...header,
    ...rows([...correct].sort((a, b) => b.n - a.n)),
  ].join('\n')
}

export function renderMarkdown(r: EvalResults): string {
  const byKey = new Map(r.arms.map((a) => [a.key, a]))
  const agent = byKey.get('agent')!
  const agentNoLlm = byKey.get('agent_no_llm')!
  const baseline = byKey.get('baseline')!
  const cmp = r.llmComparison

  const reportedArms = r.arms.filter((a) => a.key !== 'agent_no_llm')

  const lines: string[] = []

  lines.push('# Eval results')
  lines.push('')
  lines.push(
    'Generated by `npm run eval`. Do not edit by hand — every number in the README is copied from this file.',
  )
  lines.push('')
  lines.push(
    `Dataset \`${r.datasetVersion}\`, \`${r.split}\` split, ${r.recordCount} records. Generated ${r.generatedAt}.`,
  )
  if (r.skipped > 0) {
    lines.push('')
    lines.push(`${r.skipped} records were skipped for a missing oracle or true cause.`)
  }
  lines.push('')

  lines.push('## The LLM trade-off')
  lines.push('')
  lines.push(
    'This is the most interesting result in the project, and it is a trade rather than a win. Turning the model on recovers more money and more payments, and it does so while classifying slightly *worse* and roughly doubling the attempts spent on payments that could never have recovered.',
  )
  lines.push('')
  lines.push('| | LLM off | LLM on | change |')
  lines.push('|---|---|---|---|')
  lines.push(
    `| payments recovered | ${rate(cmp.recoveredOff, r.recordCount)} | ${rate(cmp.recoveredOn, r.recordCount)} | ${cmp.recoveredOn - cmp.recoveredOff >= 0 ? '+' : ''}${cmp.recoveredOn - cmp.recoveredOff} |`,
  )
  lines.push(
    `| money recovered | ${rupees(cmp.recoveredPaiseOff)} | ${rupees(cmp.recoveredPaiseOn)} | ${rupees(cmp.recoveredPaiseOn - cmp.recoveredPaiseOff)} |`,
  )
  lines.push(
    `| classification accuracy | ${rate(cmp.correctOff, cmp.classifiedTotal)} | ${rate(cmp.correctOn, cmp.classifiedTotal)} | ${cmp.correctOn - cmp.correctOff >= 0 ? '+' : ''}${cmp.correctOn - cmp.correctOff} |`,
  )
  lines.push(
    `| wasted charge attempts | ${cmp.wastedOff} | ${cmp.wastedOn} | ${cmp.wastedOn - cmp.wastedOff >= 0 ? '+' : ''}${cmp.wastedOn - cmp.wastedOff} |`,
  )
  lines.push(
    `| total charge attempts | ${cmp.chargeAttemptsOff} | ${cmp.chargeAttemptsOn} | ${cmp.chargeAttemptsOn - cmp.chargeAttemptsOff >= 0 ? '+' : ''}${cmp.chargeAttemptsOn - cmp.chargeAttemptsOff} |`,
  )
  lines.push('')
  lines.push(
    `LLM hit rate: ${rate(cmp.llmHitRate.calls, cmp.llmHitRate.total)} of records required a model call. The PRD target was under 15%; see docs/EVAL-PLAN.md for why that target is not reachable alongside a meaningful OPAQUE_BANK_DECLINE metric.`,
  )
  lines.push('')
  lines.push(
    'The mechanism is not subtle. With the model off, every opaque decline falls back to `UNKNOWN` and escalates without acting, which spends nothing and recovers nothing. With the model on, those records get a predicted cause and run a playbook — and a playbook that runs on a wrong cause still spends attempts. The model buys recovery with wasted effort. Whether that is worth it depends on the per-attempt cost, which is why the cost assumptions below are stated rather than hidden.',
  )
  lines.push('')

  lines.push('## Arms')
  lines.push('')
  lines.push(
    '| arm | recovered | money recovered | of total value | charge attempts | wasted | contacts | attempts per recovery |',
  )
  lines.push('|---|---|---|---|---|---|---|---|')
  for (const m of reportedArms) lines.push(`| ${armRow(m)} |`)
  lines.push(`| ${armRow(agentNoLlm)} |`)
  lines.push('')
  lines.push(
    `Total value at risk across the split: ${rupees(baseline.totalPaise)} over ${r.recordCount} failed payments.`,
  )
  lines.push('')

  const lift = agent.recovered - baseline.recovered
  const liftPaise = agent.recoveredPaise - baseline.recoveredPaise
  lines.push('### Lift over baseline')
  lines.push('')
  lines.push(
    `- Payments: ${lift >= 0 ? '+' : ''}${lift} (${rate(agent.recovered, r.recordCount)} against ${rate(baseline.recovered, r.recordCount)})`,
  )
  lines.push(
    `- Money: ${rupees(liftPaise)} (${rupees(agent.recoveredPaise)} against ${rupees(baseline.recoveredPaise)})`,
  )
  lines.push(
    `- Wasted charge attempts: ${agent.wastedChargeAttempts - baseline.wastedChargeAttempts >= 0 ? '+' : ''}${agent.wastedChargeAttempts - baseline.wastedChargeAttempts} (${agent.wastedChargeAttempts} against ${baseline.wastedChargeAttempts})`,
  )
  lines.push('')

  lines.push('## Cost')
  lines.push('')
  lines.push('Assumed values, declared rather than measured:')
  lines.push('')
  for (const a of r.costAssumptions) lines.push(`- ${a}`)
  lines.push('')
  lines.push('| arm | operational cost | money recovered | cost per recovery |')
  lines.push('|---|---|---|---|')
  for (const m of [...reportedArms, agentNoLlm]) {
    lines.push(
      `| ${m.label} | ${rupees(m.operationalCostPaise)} | ${rupees(m.recoveredPaise)} | ${m.recovered === 0 ? 'n/a' : rupees(Math.round(m.operationalCostPaise / m.recovered))} |`,
    )
  }
  lines.push('')

  lines.push('## Customer impact')
  lines.push('')
  lines.push('| arm | contacts | contacts per recovery | quiet-hours violations | escalated | vetoed |')
  lines.push('|---|---|---|---|---|---|')
  for (const m of [...reportedArms, agentNoLlm]) {
    lines.push(
      `| ${m.label} | ${m.contacts} | ${ratio(m.contacts, m.recovered)} | ${m.quietHoursViolations} | ${m.escalated} | ${m.vetoed} |`,
    )
  }
  lines.push('')
  lines.push(
    'Quiet-hours violations are checked by re-deriving the customer-local hour of every delivered nudge, not by trusting the guardrail. A non-zero value here is a bug, not a metric.',
  )
  lines.push('')
  lines.push('### Guardrail vetoes, agent arm (LLM on)')
  lines.push('')
  const vetoEntries = Object.entries(agent.vetoedBy).sort((a, b) => b[1] - a[1])
  if (vetoEntries.length === 0) {
    lines.push('No vetoes fired.')
  } else {
    lines.push('| rule | payments stopped |')
    lines.push('|---|---|')
    for (const [rule, n] of vetoEntries) lines.push(`| \`${rule}\` | ${n} |`)
  }
  lines.push('')

  lines.push('## Recovery by true cause')
  lines.push('')
  const causes = Object.keys(agent.byCause).sort()
  lines.push('| true cause | n | baseline | agent (LLM on) | agent (LLM off) | majority class |')
  lines.push('|---|---|---|---|---|---|')
  const majority = byKey.get('majority_class')!
  for (const cause of causes) {
    const n = agent.byCause[cause]!.total
    const cell = (m: ArmMetrics): string => {
      const b = m.byCause[cause]
      return b === undefined ? '0/0' : rate(b.recovered, b.total)
    }
    lines.push(
      `| \`${cause}\` | ${n} | ${cell(baseline)} | ${cell(agent)} | ${cell(agentNoLlm)} | ${cell(majority)} |`,
    )
  }
  lines.push('')

  lines.push('## Classification')
  lines.push('')
  for (const key of ['agent', 'agent_no_llm', 'majority_class']) {
    const c = r.classification[key]
    const m = byKey.get(key)
    if (c === undefined || m === undefined) continue
    lines.push(`### ${m.label}`)
    lines.push('')
    lines.push(`Overall accuracy ${rate(c.correct, c.total)}.`)
    lines.push('')
    lines.push('| cause | support | predicted | tp | fp | fn | precision | recall |')
    lines.push('|---|---|---|---|---|---|---|---|')
    for (const p of c.perClass) {
      if (p.support === 0 && p.predicted === 0) continue
      lines.push(
        `| \`${p.cause}\` | ${p.support} | ${p.predicted} | ${p.tp} | ${p.fp} | ${p.fn} | ${p.predicted === 0 ? 'n/a' : rate(p.tp, p.predicted)} | ${p.support === 0 ? 'n/a' : rate(p.tp, p.support)} |`,
      )
    }
    lines.push('')
  }

  const risk = r.classification['agent']?.perClass.find((p) => p.cause === 'RISK_DECLINE')
  if (risk !== undefined) {
    lines.push('### RISK_DECLINE recall')
    lines.push('')
    lines.push(
      `${rate(risk.tp, risk.support)} risk declines correctly identified. This is the safety-critical class: a missed risk decline is a payment the agent might retry when it must never retry. \`PERMANENT_FAILURE_BLOCK\` vetoes every charge retry on this cause independently of the classifier, so a miss only costs recovery effort if the record is misrouted into a retrying playbook.`,
    )
    lines.push('')
  }

  lines.push('## The opaque subset')
  lines.push('')
  lines.push('This is the class where the model does inference rather than confirming a lookup, so it is the honest test of whether the model adds anything.')
  lines.push('')
  for (const key of ['agent', 'agent_no_llm']) {
    const o = r.opaque[key]
    const m = byKey.get(key)
    if (o === undefined || m === undefined) continue
    lines.push(`### ${m.label}`)
    lines.push('')
    lines.push(opaqueSection(o))
    lines.push('')
  }

  lines.push('## Cost-weighted confusion matrix')
  lines.push('')
  lines.push('Agent arm, LLM on.')
  lines.push('')
  lines.push(confusionSection(r.confusion))
  lines.push('')

  lines.push('## How to read these numbers')
  lines.push('')
  for (const c of r.caveats) lines.push(`- ${c}`)
  lines.push('')

  return lines.join('\n')
}
